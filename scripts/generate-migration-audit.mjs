#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = "prisma/migrations";
const entries = readdirSync(root, { withFileTypes: true });

const migrations = [];
for (const entry of entries) {
  if (entry.isFile() && entry.name.endsWith(".sql")) {
    migrations.push({ name: entry.name, path: join(root, entry.name), canonical: false });
  } else if (entry.isDirectory()) {
    const file = join(root, entry.name, "migration.sql");
    try {
      readFileSync(file, "utf8");
      migrations.push({ name: entry.name, path: file, canonical: /^\d{14}_/.test(entry.name) });
    } catch {
      // ignore
    }
  }
}

migrations.sort((a, b) => a.name.localeCompare(b.name));

const tableCreates = new Map();
for (const migration of migrations) {
  const sql = readFileSync(migration.path, "utf8");
  const matches = [...sql.matchAll(/CREATE TABLE IF NOT EXISTS\s+([a-zA-Z0-9_]+)/g)];
  for (const m of matches) {
    const table = m[1];
    if (!tableCreates.has(table)) tableCreates.set(table, []);
    tableCreates.get(table).push(migration.name);
  }
}

let md = "# Migration Audit\n\n";
md +=
  "Generated by `node scripts/generate-migration-audit.mjs` from repository files only (no live DB access).\n\n";
md += "## Ordered migration artifacts\n\n";
for (const migration of migrations) {
  md += `- ${migration.name} (${migration.path})${migration.canonical ? "" : " ⚠️ non-standard filename/location"}\n`;
}

const nonCanonical = migrations.filter((m) => !m.canonical);
md += "\n## Findings\n\n";
if (nonCanonical.length > 0) {
  md += `- Found ${nonCanonical.length} non-canonical migration artifacts not in Prisma timestamp directory format. These are not guaranteed to be tracked by Prisma migrate history.\n`;
}

const duplicateTables = [...tableCreates.entries()].filter(([, origins]) => origins.length > 1);
if (duplicateTables.length > 0) {
  md += `- Found ${duplicateTables.length} tables defined across multiple files (potential overlap/conditional idempotency).\n`;
  for (const [table, origins] of duplicateTables.slice(0, 20)) {
    md += `  - ${table}: ${origins.join(", ")}\n`;
  }
}

md += "\n## Remaining migration execution recommendation\n\n";
md +=
  "Because live `_prisma_migrations` state is unavailable, run migrations in filename order below and verify checksum/history in target DB before applying any non-canonical `.sql` files manually.\n\n";
for (const migration of migrations) {
  md += `1. ${migration.path}\n`;
}

writeFileSync("docs/verification/migration-audit.md", md);
console.log("Wrote docs/verification/migration-audit.md");
