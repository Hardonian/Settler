#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

const variables = [
  "NEXT_PUBLIC_SUPABASE_URL",
  "NEXT_PUBLIC_SUPABASE_ANON_KEY",
  "SUPABASE_URL",
  "SUPABASE_ANON_KEY",
  "SUPABASE_SERVICE_ROLE_KEY",
  "DATABASE_URL",
  "SUPABASE_DATABASE_URL",
  "DIRECT_URL",
  "SUPABASE_DB_URL",
  "VERCEL_",
  "DOPPLER_",
];

const rgPattern = variables.join("|");
const output = execSync(
  `rg -n "${rgPattern}" packages scripts prisma.config.ts turbo.json next.config.js packages/web/next.config.js .github/workflows --glob '!**/node_modules/**' --glob '!**/dist/**'`,
  { encoding: "utf8" }
);
const lines = output.trim().split("\n").filter(Boolean);

const summary = new Map();
for (const line of lines) {
  const [file, lineNo, ...rest] = line.split(":");
  const text = rest.join(":");
  for (const name of variables.filter((v) => !v.endsWith("_"))) {
    if (text.includes(name)) {
      if (!summary.has(name)) summary.set(name, []);
      summary.get(name).push({ file, line: Number(lineNo), text: text.trim() });
    }
  }
  if (/VERCEL_[A-Z0-9_]+/.test(text)) {
    const matches = text.match(/VERCEL_[A-Z0-9_]+/g) || [];
    for (const name of matches) {
      if (!summary.has(name)) summary.set(name, []);
      summary.get(name).push({ file, line: Number(lineNo), text: text.trim() });
    }
  }
  if (/DOPPLER_[A-Z0-9_]+/.test(text)) {
    const matches = text.match(/DOPPLER_[A-Z0-9_]+/g) || [];
    for (const name of matches) {
      if (!summary.has(name)) summary.set(name, []);
      summary.get(name).push({ file, line: Number(lineNo), text: text.trim() });
    }
  }
}

let md = "# Environment Resolution Audit\n\n";
md += "Generated by `node scripts/generate-env-resolution-audit.mjs`.\n\n";
md += "| Variable | Files | Runtime Surface | Notes |\n|---|---:|---|---|\n";
for (const [name, entries] of [...summary.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  const surfaces = new Set(
    entries.map((entry) =>
      entry.file.includes("packages/web/src/app") || entry.file.includes("packages/web/src/lib")
        ? "web-runtime"
        : entry.file.includes(".github/workflows")
          ? "ci"
          : entry.file.includes("turbo.json") || entry.file.includes("next.config")
            ? "build"
            : "script/server"
    )
  );
  const note = entries.some((e) => e.text.includes("||"))
    ? "contains fallback/alias logic"
    : "direct usage";
  md += `| ${name} | ${entries.length} | ${[...surfaces].join(", ")} | ${note} |\n`;
}

md += "\n## Representative call sites\n";
for (const [name, entries] of [...summary.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  const top = entries
    .slice(0, 5)
    .map((entry) => `- \`${entry.file}:${entry.line}\` → \`${entry.text}\``)
    .join("\n");
  md += `\n### ${name}\n${top || "- none"}\n`;
}

writeFileSync("docs/verification/env-resolution-audit.md", md);
console.log("Wrote docs/verification/env-resolution-audit.md");
